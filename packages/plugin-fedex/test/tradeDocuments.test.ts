import RequestHandler, { buildClientName, memoryBackend } from "@dianemo/core";
import { createServer, type IncomingMessage, type Server } from "node:http";
import * as tradeDocuments from "../src/requests/tradeDocuments/index.js";
import { afterEach, describe, expect, it, vi } from "vitest";
import { resetBinding } from "@dianemo/plugin-kit/testing";
import { TEST_KEY } from "../../../test/fixtures/key.js";
import type { AddressInfo } from "node:net";
import fedex from "../src/index.js";
import type {
  FedExMultiDocumentInformation,
  FedExUploadEncodedImageRequest,
  FedExUploadMultipleEncodedEtdDocumentsRequest,
} from "../src/requests/tradeDocuments/types.js";

const newHandler = () =>
  new RequestHandler({ key: TEST_KEY, backend: memoryBackend() });
const CLIENT = "fedex:_:production";
const DOCS = "fedex:_:production:documents";

afterEach(() => resetBinding());

interface ClientData {
  rateLimit: Array<{ type: string }>;
  authOwnerName?: string;
  authentication: unknown;
  requestOptions: { defaults: { baseURL: string } };
}

const bytes = new Uint8Array([1, 2, 3]);

const etdDocument = {
  workflowName: "ETDPreshipment",
  name: "invoice.pdf",
  contentType: "application/pdf",
  meta: {
    shipDocumentType: "COMMERCIAL_INVOICE",
    originCountryCode: "US",
    destinationCountryCode: "IN",
  },
} as const;

const multiInfo: FedExMultiDocumentInformation = {
  workflowName: "ETDPreshipment",
  carrierCode: "FDXE",
  originCountryCode: "US",
  destinationCountryCode: "CA",
  metaData: [
    { fileName: "a.png", contentType: "image/png", shipDocumentType: "OTHER" },
    { fileName: "b.txt", contentType: "text/plain", shipDocumentType: "OTHER" },
  ],
};

const encodedImage: FedExUploadEncodedImageRequest = {
  document: {
    referenceId: "1234",
    contentType: "image/png",
    meta: {
      imageType: "SIGNATURE",
      imageIndex: "IMAGE_1",
      fileContentBase64: "AAAA",
    },
  },
};

const encodedMulti: FedExUploadMultipleEncodedEtdDocumentsRequest = {
  workflowName: "ETDPreshipment",
  carrierCode: "FDXE",
  originCountryCode: "US",
  destinationCountryCode: "CA",
  metaData: [
    {
      contentType: "image/png",
      shipDocumentType: "ETD_LABEL",
      fileContentBase64: "AAAA",
    },
  ],
};

function spied() {
  const handler = newHandler();
  const spy = vi
    .spyOn(handler, "handleRequest")
    .mockResolvedValue({ data: { ok: true } } as never);
  handler.use(fedex);
  const requests = tradeDocuments;
  return { spy, requests };
}

const lastConfig = (spy: ReturnType<typeof spied>["spy"]) =>
  spy.mock.calls[0][0];

describe("fedex trade documents: request shape", () => {
  it("uploadEtdDocument posts a multipart form to the documents client", async () => {
    const { spy, requests } = spied();
    await requests.uploadEtdDocument(CLIENT, {
      document: etdDocument,
      attachment: bytes,
    });
    const config = lastConfig(spy);
    expect(config.clientName).toBe(DOCS);
    expect(config.requestName).toBe("fedex.tradeDocuments.uploadEtdDocument");
    expect(config.method).toBe("POST");
    expect(config.url).toBe("/documents/v1/etds/upload");

    const form = config.data as FormData;
    expect(form).toBeInstanceOf(FormData);
    expect(JSON.parse(form.get("document") as string)).toEqual(etdDocument);
    const file = form.get("attachment") as File;
    expect(file.name).toBe("invoice.pdf");
    expect(file.type).toBe("application/pdf");
    expect(new Uint8Array(await file.arrayBuffer())).toEqual(bytes);
    // Boundary is generated by axios; a header of ours would lack it.
    expect(config.headers?.["Content-Type"]).toBeUndefined();
  });

  it("uploadImage sends document, rules and attachment as sibling parts", async () => {
    const { spy, requests } = spied();
    await requests.uploadImage(CLIENT, {
      document: {
        referenceId: "1234",
        name: "LH2.PNG",
        contentType: "image/png",
        meta: { imageType: "LETTERHEAD", imageIndex: "IMAGE_2" },
      },
      rules: { workflowName: "LetterheadSignature" },
      attachment: new Blob([bytes]),
    });
    const config = lastConfig(spy);
    expect(config.clientName).toBe(DOCS);
    expect(config.requestName).toBe("fedex.tradeDocuments.uploadImage");
    expect(config.method).toBe("POST");
    expect(config.url).toBe("/documents/v1/lhsimages/upload");
    const form = config.data as FormData;
    expect([...form.keys()].sort()).toEqual([
      "attachment",
      "document",
      "rules",
    ]);
    expect(JSON.parse(form.get("rules") as string)).toEqual({
      workflowName: "LetterheadSignature",
    });
    expect((form.get("attachment") as File).name).toBe("LH2.PNG");
  });

  it("uploadEncodedImage posts JSON unchanged", async () => {
    const { spy, requests } = spied();
    await requests.uploadEncodedImage(CLIENT, encodedImage);
    const config = lastConfig(spy);
    expect(config.clientName).toBe(DOCS);
    expect(config.requestName).toBe("fedex.tradeDocuments.uploadEncodedImage");
    expect(config.method).toBe("POST");
    expect(config.url).toBe("/documents/v1/lhsimages/encodedupload");
    expect(config.data).toEqual(encodedImage);
  });

  it("uploadMultipleEtdDocuments repeats fileAttachments, named from metaData", async () => {
    const { spy, requests } = spied();
    await requests.uploadMultipleEtdDocuments(CLIENT, {
      documentInformation: multiInfo,
      fileAttachments: [bytes, bytes],
    });
    const config = lastConfig(spy);
    expect(config.clientName).toBe(DOCS);
    expect(config.requestName).toBe(
      "fedex.tradeDocuments.uploadMultipleEtdDocuments"
    );
    expect(config.method).toBe("POST");
    expect(config.url).toBe("/documents/v1/etds/multiupload");
    const form = config.data as FormData;
    expect(JSON.parse(form.get("documentInformation") as string)).toEqual(
      multiInfo
    );
    const files = form.getAll("fileAttachments") as File[];
    expect(files.map((f) => [f.name, f.type])).toEqual([
      ["a.png", "image/png"],
      ["b.txt", "text/plain"],
    ]);
  });

  it("uploadMultipleEncodedEtdDocuments posts JSON unchanged", async () => {
    const { spy, requests } = spied();
    await requests.uploadMultipleEncodedEtdDocuments(CLIENT, encodedMulti);
    const config = lastConfig(spy);
    expect(config.clientName).toBe(DOCS);
    expect(config.requestName).toBe(
      "fedex.tradeDocuments.uploadMultipleEncodedEtdDocuments"
    );
    expect(config.method).toBe("POST");
    expect(config.url).toBe("/documents/v1/etds/encodedmultiupload");
    expect(config.data).toEqual(encodedMulti);
  });
});

describe("fedex trade documents: client layout", () => {
  async function build(baseUrl: string) {
    const handler = newHandler();
    handler.use(fedex);
    await handler.addTemplateClient(
      "fedex" as never,
      {
        instanceId: "production",
        clientId: "id",
        clientSecret: "secret",
        baseUrl,
      } as never
    );
    const clients = (
      handler as unknown as {
        clients: Map<string, { sourceClientData: ClientData }>;
      }
    ).clients;
    const data = (name: string) => clients.get(name)!.sourceClientData;
    return { clients, data };
  }

  it.each([
    ["https://apis.fedex.com", "https://documentapi.prod.fedex.com"],
    [
      "https://apis-sandbox.fedex.com",
      "https://documentapitest.prod.fedex.com/sandbox",
    ],
    ["http://127.0.0.1:9", "http://127.0.0.1:9"],
  ])("maps %s to the document host %s", async (baseUrl, documentHost) => {
    const { data } = await build(baseUrl);
    expect(data(CLIENT).requestOptions.defaults.baseURL).toBe(baseUrl);
    expect(data(DOCS).requestOptions.defaults.baseURL).toBe(documentHost);
  });

  it("keeps the existing leaf usable and draws documents on its budget", async () => {
    const { clients, data } = await build("https://apis.fedex.com");
    expect([...clients.keys()].filter((n) => n !== "default").sort()).toEqual([
      CLIENT,
      DOCS,
    ]);
    expect(data(CLIENT).rateLimit[0].type).toBe("requestLimit");
    expect(data(DOCS).rateLimit).toEqual([
      { type: "sharedLimit", clientName: CLIENT },
    ]);
    // One token, minted by the parent: the sub-client stores no credentials of its own.
    expect(data(DOCS).authOwnerName).toBe(CLIENT);
    expect(data(DOCS).authentication).toEqual(data(CLIENT).authentication);
  });

  it("builds the documents name from buildClientName, never by hand", () => {
    expect(
      buildClientName("fedex", { instanceId: "production" } as never) +
        ":documents"
    ).toBe(DOCS);
  });
});

describe("fedex trade documents: over the wire", () => {
  async function listen(): Promise<{
    server: Server;
    seen: Array<{
      url?: string;
      headers: IncomingMessage["headers"];
      body: string;
    }>;
  }> {
    const seen: Array<{
      url?: string;
      headers: IncomingMessage["headers"];
      body: string;
    }> = [];
    const server = createServer((req, res) => {
      const chunks: Buffer[] = [];
      req.on("data", (c) => chunks.push(c));
      req.on("end", () => {
        seen.push({
          url: req.url,
          headers: req.headers,
          body: Buffer.concat(chunks).toString("latin1"),
        });
        res.setHeader("content-type", "application/json");
        res.end(
          req.url === "/oauth/token"
            ? JSON.stringify({ access_token: "tok", expires_in: 3600 })
            : JSON.stringify({ output: { meta: { docId: "d1" } } })
        );
      });
    });
    await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
    return { server, seen };
  }

  it("sends a real multipart body, with a boundary and the inherited bearer token", async () => {
    const { server, seen } = await listen();
    const baseUrl = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
    try {
      const handler = newHandler();
      handler.use(fedex);
      const requests = tradeDocuments;
      await handler.addTemplateClient(
        "fedex" as never,
        {
          instanceId: "production",
          clientId: "id",
          clientSecret: "secret",
          baseUrl,
        } as never
      );

      const res = await requests.uploadEtdDocument(CLIENT, {
        document: etdDocument,
        attachment: bytes,
      });

      expect(res.output?.meta?.docId).toBe("d1");
      const upload = seen.find((r) => r.url === "/documents/v1/etds/upload");
      expect(upload?.headers.authorization).toBe("Bearer tok");
      expect(upload?.headers["content-type"]).toMatch(
        /^multipart\/form-data; boundary=/
      );
      expect(upload?.body).toContain('name="document"');
      expect(upload?.body).toContain(
        'name="attachment"; filename="invoice.pdf"'
      );
      await handler.stop();
    } finally {
      server.close();
    }
  });
});
